"""DEP-REMEDIATE-003 — nested Console retirement ledger is complete and truthful.

Validates docs/security/dep_remediate_003_retirement_ledger.json (generated by
tools/ci/dep_remediate_003_ledger.py) against the current tree:

  * every legacy test has an allowed state, and none is BLOCKED;
  * every mapping names a canonical test that exists in apps/console/tests;
  * every OBSOLETE decision cites commit or PR evidence;
  * summary counts equal the entries;
  * none of the retired files is still tracked, and the guard policy and
    DEP-INV-001 authority both mark the tree retired.
"""

from __future__ import annotations

import json
import re
import subprocess
from collections import Counter
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
LEDGER = REPO / "docs/security/dep_remediate_003_retirement_ledger.json"
STATES = {"MIGRATED", "ALREADY_COVERED", "OBSOLETE_WITH_EVIDENCE", "BLOCKED"}
RETIRED = "apps/console/console"


@pytest.fixture(scope="module")
def ledger() -> dict:
    return json.loads(LEDGER.read_text())


def _tracked() -> set[str]:
    out = subprocess.run(
        ["git", "-C", str(REPO), "ls-files", "-z"], capture_output=True, check=True
    ).stdout
    return {p for p in out.decode().split("\0") if p}


def test_ledger_identity(ledger: dict) -> None:
    assert ledger["schema"] == "fg.legacy_tree_retirement/v1"
    assert ledger["work_item"] == "DEP-REMEDIATE-003"
    assert ledger["retired_root"] == RETIRED
    assert re.fullmatch(r"[0-9a-f]{40}", ledger["source_commit"])


def test_every_legacy_test_has_an_allowed_state_and_none_blocked(ledger: dict) -> None:
    states = Counter(e["state"] for e in ledger["test_ledger"])
    assert set(states) <= STATES
    assert states.get("BLOCKED", 0) == 0


def test_summary_matches_entries(ledger: dict) -> None:
    s, tests, files = ledger["summary"], ledger["test_ledger"], ledger["file_inventory"]
    assert s["legacy_tests"] == len(tests) == 712
    assert s["legacy_test_files"] == len({e["legacy_file"] for e in tests}) == 15
    assert s["legacy_tests_by_state"] == dict(Counter(e["state"] for e in tests))
    sec = [e for e in tests if e["security_relevant"]]
    assert s["security_relevant_legacy_tests"] == len(sec)
    assert s["security_relevant_by_state"] == dict(Counter(e["state"] for e in sec))
    assert s["files_deleted"] == len(files) == 118
    assert sum(s["files_by_comparison"].values()) == len(files)
    assert s["nested_assertions_holding_on_active_source"] == sum(
        e["nested_assertions_hold_on_active_source"] for e in tests
    )
    # Test-count change is fully explained: 712 legacy removed, new behavioural added.
    added = sum(s["new_behavioural_tests"].values())
    assert (
        s["console_tests_after_observed"]
        == s["console_tests_before_observed"] - 712 + added
    )


def test_every_mapping_names_an_existing_canonical_test(ledger: dict) -> None:
    sources: dict[str, str] = {}
    for e in ledger["test_ledger"]:
        f = e["canonical_file"]
        assert f.startswith("apps/console/tests/"), e
        src = sources.setdefault(f, (REPO / f).read_text())
        title = e["canonical_test_source_title"]
        assert any(f"{q}{title}{q}" in src for q in ("'", '"', "`")), (
            f"{f} has no test titled {title!r} (ledger entry {e['legacy_test']!r})"
        )


def test_evidence_is_present_and_obsolete_decisions_cite_history(ledger: dict) -> None:
    evidence = ledger["evidence"]
    for e in ledger["test_ledger"]:
        assert e["evidence_id"] in evidence, e
        if e["state"] == "OBSOLETE_WITH_EVIDENCE":
            assert re.search(
                r"\b[0-9a-f]{9}\b|#\d+|PR \d+", evidence[e["evidence_id"]]
            ), e
        if not e["nested_assertions_hold_on_active_source"]:
            # A legacy assertion that no longer holds must never be waved through
            # with the "identical coverage" evidence.
            assert "also pass against the active" not in evidence[e["evidence_id"]], e


def test_security_relevant_rate_limit_reversal_is_recorded_not_hidden(
    ledger: dict,
) -> None:
    obsolete_sec = {
        e["legacy_test"]
        for e in ledger["test_ledger"]
        if e["security_relevant"] and e["state"] == "OBSOLETE_WITH_EVIDENCE"
    }
    assert obsolete_sec == {
        "redis_outage_does_not_fail_open_in_prod",
        "route_passes_errorCode_through_to_503_response",
        "redis_unavailable_in_prod_returns_stable_error",
    }
    for key, text in ledger["evidence"].items():
        if "225d21c25" in text:
            assert "residual risk R1" in text, key


def test_retired_files_are_gone_and_tree_is_marked_retired(ledger: dict) -> None:
    tracked = _tracked()
    for item in ledger["file_inventory"]:
        assert item["path"].startswith(f"{RETIRED}/")
        assert item["decision"] == "DELETE"
        assert item["runtime_reachable"] is False
        assert re.fullmatch(r"[0-9a-f]{64}", item["sha256"])
        assert item["path"] not in tracked, item["path"]
    assert not any(p.startswith(f"{RETIRED}/") for p in tracked)
    policy = json.loads((REPO / ".github/security/lockfile-authority.json").read_text())
    assert RETIRED in policy["retired_roots"]
    inv = (REPO / "tools/ci/dependency_alert_inventory.py").read_text()
    assert re.search(
        r'"apps/console/console/package-lock\.json": \{\s*"status": "RETIRED"', inv
    )


def test_nested_only_tenant_switcher_is_not_reintroduced_anywhere() -> None:
    # The nested tree held the last copy of the client-side tenant switcher that
    # #706 deliberately deleted from the active Console.
    assert not any(p.endswith("/TenantSwitcher.tsx") for p in _tracked())


def test_behavioural_replacement_suite_is_discovered_by_npm_test() -> None:
    f = REPO / "apps/console/tests/rate-limit-store-behavior.test.js"
    assert f.exists()
    pkg = json.loads((REPO / "apps/console/package.json").read_text())
    assert (
        pkg["scripts"]["test"] == "node --test"
    )  # default discovery picks up *.test.js
    src = f.read_text()
    assert "lib', 'rateLimitStore.ts'" in src
    assert "transpileModule" in src
